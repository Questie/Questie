"""Generated outputs of the color contrast tool: banned.lua, the CSVs, per-zone review sheets and the overview.
The crop and blob drawing is shared with calibration.py's rating cells, so ratings judge what the sheets show."""

from __future__ import annotations

import csv
import re
from pathlib import Path
from typing import TYPE_CHECKING

import numpy as np
from PIL import Image, ImageDraw, ImageFont

from sources import ART_HEIGHT, ART_WIDTH, Flavor, Minimap, PaletteColor, Zone

if TYPE_CHECKING:
    from colorcontrast import Settings, Terrain, ZoneResult

CELL = 128  # pixels per crop in the zone sheets
GAP = 6
LABEL_WIDTH = 260
MAP_CROP_RADIUS = 64  # art pixels per CELL / 2, so a cell shows the world map near its in-game size
MINIMAP_CROP_YARDS = 700 / 3  # radius of the minimap at its widest zoom (466 2/3 yards across)
BLOB_BOX = (0.15, 0.24, 0.85, 0.76)  # the blob ellipse's bounds as fractions of a cell
SUPERSAMPLE = 4  # blob edges are drawn this much larger, then scaled down smoothly

BACKGROUND = (24, 24, 28)
TEXT = (230, 230, 230)
DIM = (140, 140, 140)
RED = (235, 70, 60)
AMBER = (240, 170, 50)
GREEN = (90, 200, 110)


def _font(size: int) -> ImageFont.ImageFont:
    try:
        return ImageFont.load_default(size=size)
    except (TypeError, OSError):  # Pillow without FreeType: fixed-size bitmap font
        return ImageFont.load_default()


def _worst(result: ZoneResult, index: int) -> tuple[float, Terrain]:
    """The lowest fill score of a color over the zone's terrains, and that terrain."""
    terrain = min(result.terrains, key=lambda t: t.scores[index][0])
    return terrain.scores[index][0], terrain


def _faint_view(result: ZoneResult, index: int) -> tuple[str, float]:
    """The view a color is too faint on the most of, and that share of its ground."""
    return max(result.faint_shares[index].items(), key=lambda item: item[1])


def _coordinates(terrain: Terrain) -> str:
    return f"{terrain.spot[0] * 100:.1f}, {terrain.spot[1] * 100:.1f}"


def _settings_text(settings: Settings) -> str:
    w = settings.weights
    thresholds = ", ".join(f"{view} faint {settings.faint[view]:.2f}"
                           + (f" clear {settings.clear[view]:.2f}" if settings.clear[view] is not None else "")
                           for view in ("map", "minimap"))
    return (f"weights L {w.lightness:g} a {w.red_green:g} blue {w.blue:g} yellow {w.yellow:g} · {thresholds} · "
            f"max-faint-share {settings.max_faint_share:g} · p{settings.percentile:g}")


# banned.lua and the CSVs

def write_banned_lua(results: list[ZoneResult], palette: list[PaletteColor], settings: Settings, path: Path) -> None:
    names = {color.index: color.name for color in palette}
    # Palette health, for a person to watch across runs: a color creeping toward most zones is a candidate to
    # retire by hand. Nothing here retires colors.
    counts = {color.index: sum(color.index in result.banned for result in results) for color in palette}
    health = ", ".join(f"{names[i]} {n}" for i, n in sorted(counts.items(), key=lambda item: -item[1]) if n)
    lines = [
        "-- Generated by ExternalScripts(DONOTINCLUDEINRELEASE)/ColorContrast/colorcontrast.py; rerun it instead of editing.",
        "-- Objective palette indexes (ObjectiveColors PALETTE) too faint as blobs on a zone's map or minimap.",
        f"-- {_settings_text(settings)}",
        f"-- Zones banned per color (of {len(results)}): {health or 'none'}",
        "return {",
    ]
    for result in sorted(results, key=lambda r: r.zone.ui_map_id):
        indexes = sorted(result.banned)
        names_text = ", ".join(names[i] for i in indexes) or "none"
        overridden = "; ".join(f"{verdict} {names[i]} by hand" for i, (verdict, _) in sorted(result.overrides.items()))
        lines.append(f"    [{result.zone.ui_map_id}] = {{{', '.join(map(str, indexes))}}}, "
                     f"-- {result.zone.name}: {names_text}" + (f" ({overridden})" if overridden else ""))
    lines.append("}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


LUA_LINE_LIMIT = 140  # luacheck's max line length


def _lua_line(code: str, comment: str) -> str:
    """A line of code with a trailing comment, the comment shortened (never the code) to stay within luacheck's
    line limit."""
    if len(code) > LUA_LINE_LIMIT - 7:  # room for " -- ..."
        raise ValueError(f"generated Lua line too long for luacheck: {code}")
    line = f"{code} -- {comment}"
    return line if len(line) <= LUA_LINE_LIMIT else line[:LUA_LINE_LIMIT - 3] + "..."


def _wrapped(items: list[str], indent: str, width: int = 120) -> list[str]:
    """Lua list items, each followed by a comma, packed into lines of at most width characters."""
    lines, line = [], indent
    for item in items:
        if len(line) + len(item) + 2 > width and line != indent:
            lines.append(line.rstrip())
            line = indent
        line += f"{item}, "
    lines.append(line.rstrip())
    return lines


def write_addon_bans(results: list[ZoneResult], palette: list[PaletteColor], settings: Settings, flavor: Flavor,
                     opacity: tuple[float, float], path: Path | None = None) -> None:
    """The flavor's shipped ban data: a Lua file that registers with ObjectiveColors.AddBans, loaded by the flavor's
    TOCs. Bans name their colors, so a palette change never makes them ban the wrong ones. The file also records the
    TOCs meant to load it, each color's sRGB and the blob opacity it was measured with; ObjectiveColors.test.lua
    checks those against the live TOCs, palette and PolygonMinimap. Zones that allow every color are left out."""
    names = {color.index: color.name for color in palette}
    weights, faint = settings.weights, settings.faint
    color_lines = [f'        ["{color.name}"] = {{{", ".join(map(str, color.rgb))}}},' for color in palette]

    # One line per zone; a list too long for one line wraps under its zone.
    zone_lines = []
    for result in sorted(results, key=lambda r: r.zone.ui_map_id):
        if result.banned:
            banned = [f'"{names[i]}"' for i in sorted(result.banned)]
            key = f"        [{result.zone.ui_map_id}] = "
            single = f"{key}{{{', '.join(banned)}}},"
            if len(single) <= LUA_LINE_LIMIT - 7:
                zone_lines.append(_lua_line(single, result.zone.name))
            else:
                zone_lines.append(_lua_line(key + "{", result.zone.name))
                zone_lines += _wrapped(banned, " " * 12)
                zone_lines.append("        },")

    lines = [
        "-- Generated by ExternalScripts(DONOTINCLUDEINRELEASE)/ColorContrast/colorcontrast.py --write-addon;",
        "-- rerun it instead of editing.",
        f"-- Objective colors too faint as Questie blobs on {flavor.name}'s world map or minimap, per UiMapId.",
        f"-- Measured over {len(results)} zones; a zone not listed allows every color.",
        f"-- Score weights: lightness {weights.lightness:g}, red-green {weights.red_green:g}, "
        f"blue {weights.blue:g}, yellow {weights.yellow:g}.",
        f"-- Too faint below {faint['map']:.2f} on the map and {faint['minimap']:.2f} on the minimap; banned once "
        f"too faint on {settings.max_faint_share:.0%} of a view's ground.",
        f"-- Terrains: {settings.clusters} clusters per view, merged closer than {settings.merge_distance:g}; "
        f"scores at the {settings.percentile:g}th percentile.",
        "",
        "---@type ObjectiveColors",
        'local ObjectiveColors = QuestieLoader:ImportModule("ObjectiveColors")',
        "",
        "ObjectiveColors.AddBans({",
        "    tocs = {" + ", ".join(f'"{toc}"' for toc in flavor.tocs) + "},",
        f"    measuredOpacity = {{{opacity[0]:g}, {opacity[1]:g}}},",
        "    measuredColors = {",
        *color_lines,
        "    },",
        "    byUiMapId = {",
        *zone_lines,
        "    },",
        "})",
    ]
    path = path or flavor.data_file
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_csvs(results: list[ZoneResult], palette: list[PaletteColor], settings: Settings, folder: Path) -> None:
    """terrains.csv (one row per terrain) and scores.csv (one row per terrain and color). Spots are in the
    in-game 0..100 map coordinates; levels are 1 clear, 2 hard but works, 3 too faint."""
    with (folder / "terrains.csv").open("w", newline="", encoding="utf-8") as terrains_file, \
            (folder / "scores.csv").open("w", newline="", encoding="utf-8") as scores_file:
        terrains_csv, scores_csv = csv.writer(terrains_file), csv.writer(scores_file)
        terrains_csv.writerow(["ui_map_id", "zone", "view", "terrain", "share", "r", "g", "b", "spot_x", "spot_y",
                               "place"])
        scores_csv.writerow(["ui_map_id", "zone", "view", "terrain", "share", "color_index", "color", "fill",
                             "border", "level"])
        for result in sorted(results, key=lambda r: r.zone.ui_map_id):
            zone, numbers = result.zone, {}
            for terrain in result.terrains:
                number = numbers[terrain.view] = numbers.get(terrain.view, 0) + 1
                common = [zone.ui_map_id, zone.name, terrain.view, number, f"{terrain.share:.4f}"]
                terrains_csv.writerow(common + list(terrain.rgb) + [f"{terrain.spot[0] * 100:.1f}",
                                                                    f"{terrain.spot[1] * 100:.1f}", terrain.place])
                for color in palette:
                    fill, border = terrain.scores[color.index]
                    scores_csv.writerow(common + [color.index, color.name, f"{fill:.2f}", f"{border:.2f}",
                                                  settings.level(fill, terrain.view)])


# Crops and blobs, shared with the rating cells

def bare_crop(terrain: Terrain, zone: Zone, art: np.ndarray, minimap: Minimap, size: int = CELL) -> Image.Image:
    """The terrain's spot in its own view, size x size: a square of world map, or the round minimap. The map keeps
    one art pixel per pixel, so a larger size shows more of it; the minimap always shows its whole widest-zoom
    view, so a larger size draws it bigger."""
    mx, my = terrain.spot
    if terrain.view == "map":
        # Clamped so the crop stays on the art; the spot may then sit off center.
        radius = MAP_CROP_RADIUS * size / CELL
        cx = min(max(mx * ART_WIDTH, radius), ART_WIDTH - radius)
        cy = min(max(my * ART_HEIGHT, radius), ART_HEIGHT - radius)
        box = (round(cx - radius), round(cy - radius), round(cx + radius), round(cy + radius))
        return Image.fromarray(art).crop(box).resize((size, size), Image.Resampling.LANCZOS)

    crop = minimap.crop(*zone.world_position(mx, my), MINIMAP_CROP_YARDS)
    crop = crop.resize((size, size), Image.Resampling.LANCZOS)
    round_mask = Image.new("L", (size * SUPERSAMPLE, size * SUPERSAMPLE))
    ImageDraw.Draw(round_mask).ellipse((0, 0, size * SUPERSAMPLE - 1, size * SUPERSAMPLE - 1), fill=255)
    framed = Image.new("RGB", (size, size), BACKGROUND)
    framed.paste(crop, mask=round_mask.resize((size, size), Image.Resampling.LANCZOS))
    return framed


def blob_layer(rgb: tuple[int, int, int], opacity: tuple[float, float], size: int = CELL) -> Image.Image:
    """A blob as the client draws an area: an ellipse filled at the fill opacity, edged at the border opacity."""
    fill_alpha, border_alpha = opacity
    big = size * SUPERSAMPLE
    layer = Image.new("RGBA", (big, big))
    draw = ImageDraw.Draw(layer)
    box = tuple(fraction * big for fraction in BLOB_BOX)
    draw.ellipse(box, fill=(*rgb, round(255 * fill_alpha)))
    draw.ellipse(box, outline=(*rgb, round(255 * border_alpha)), width=2 * SUPERSAMPLE)
    return layer.resize((size, size), Image.Resampling.LANCZOS)


def blob_interior(size: int) -> np.ndarray:
    """Mask of the pixels inside the blob's fill, clear of its border: the ground a rating judges."""
    left, top, right, bottom = (fraction * size for fraction in BLOB_BOX)
    y, x = np.mgrid[0:size, 0:size] + 0.5
    rx, ry = (right - left) / 2, (bottom - top) / 2
    return ((x - (left + rx)) / rx) ** 2 + ((y - (top + ry)) / ry) ** 2 < 0.8


# Zone sheets

def _score_cell(crop: Image.Image, blob: Image.Image, score: float, level: int) -> Image.Image:
    """The crop with the blob on it and its fill score in the corner, framed red when too faint there and amber
    when hard to see but working."""
    cell = Image.alpha_composite(crop.convert("RGBA"), blob).convert("RGB")
    draw = ImageDraw.Draw(cell)
    accent = {1: TEXT, 2: AMBER, 3: RED}[level]
    draw.rectangle((2, CELL - 20, 40, CELL - 3), fill=BACKGROUND)
    draw.text((6, CELL - 19), f"{score:.1f}", fill=accent, font=_font(13))
    if level > 1:
        draw.rectangle((0, 0, CELL - 1, CELL - 1), outline=accent, width=3 if level == 3 else 2)
    return cell


def render_zone_sheet(result: ZoneResult, art: np.ndarray, minimap: Minimap, palette: list[PaletteColor],
                      opacity: tuple[float, float], settings: Settings, folder: Path) -> None:
    """One JPEG per zone: a column per terrain (map terrains, then minimap terrains), its bare spot on top, then a
    row per color with the blob drawn on every spot. Banned colors come first, then Allowed; each section runs
    from the color faint on the most ground to the least, so the colors nearest a ban meet in the middle."""
    zone, terrains = result.zone, result.terrains
    title, font, small = _font(22), _font(14), _font(12)
    crops = [bare_crop(terrain, zone, art, minimap) for terrain in terrains]
    order = sorted(palette, key=lambda c: (-_faint_view(result, c.index)[1], _worst(result, c.index)[0]))
    sections = [("Banned", RED, [c for c in order if c.index in result.banned]),
                ("Allowed", GREEN, [c for c in order if c.index not in result.banned])]

    header_height, terrain_header = 64, 62
    row = CELL + GAP
    height = header_height + terrain_header + row + sum(36 + len(colors) * row for _, _, colors in sections) + GAP
    sheet = Image.new("RGB", (LABEL_WIDTH + len(terrains) * row + GAP, height), BACKGROUND)
    draw = ImageDraw.Draw(sheet)

    # Title and settings
    draw.text((GAP * 2, 10), f"{zone.name} ({zone.ui_map_id}): {len(result.banned)} of {len(palette)} banned",
              fill=TEXT, font=title)
    draw.text((GAP * 2, 40), f"{_settings_text(settings)} · red: too faint · amber: hard but works",
              fill=DIM, font=small)

    # Terrain columns: view, share, place and spot, then the bare crop
    y = header_height
    numbers: dict[str, int] = {}
    for i, (terrain, crop) in enumerate(zip(terrains, crops)):
        x = LABEL_WIDTH + i * row
        numbers[terrain.view] = numbers.get(terrain.view, 0) + 1
        draw.rectangle((x, y + 2, x + 12, y + 14), fill=terrain.rgb, outline=TEXT)
        draw.text((x + 18, y), f"{terrain.view} {numbers[terrain.view]} · {terrain.share:.0%}", fill=TEXT, font=font)
        draw.text((x, y + 20), terrain.place[:20], fill=TEXT, font=small)
        draw.text((x, y + 36), _coordinates(terrain), fill=DIM, font=small)
        sheet.paste(crop, (x, y + terrain_header))
    y += terrain_header + row

    # Banned, then Allowed: a row per color
    for name, accent, colors in sections:
        draw.text((GAP * 2, y + 8), f"{name} ({len(colors)})", fill=accent, font=title)
        y += 36
        for color in colors:
            view, share = _faint_view(result, color.index)
            draw.rectangle((GAP * 2, y + 4, GAP * 2 + 26, y + 30), fill=color.rgb)
            draw.text((GAP * 2 + 36, y + 4), f"{color.index} {color.name}", fill=TEXT, font=font)
            draw.text((GAP * 2 + 36, y + 24), "rgb {}, {}, {}".format(*color.rgb), fill=DIM, font=small)
            if share:
                draw.text((GAP * 2 + 36, y + 42), f"too faint on {share:.0%} of {view}", fill=DIM, font=small)
            if color.index in result.overrides:
                verdict, note = result.overrides[color.index]
                draw.text((GAP * 2 + 36, y + 58), f"{verdict} by hand: {note}"[:34], fill=AMBER, font=small)
            blob = blob_layer(color.rgb, opacity)
            for i, (terrain, crop) in enumerate(zip(terrains, crops)):
                fill = terrain.scores[color.index][0]
                sheet.paste(_score_cell(crop, blob, fill, settings.level(fill, terrain.view)),
                            (LABEL_WIDTH + i * row, y))
            y += row

    slug = re.sub(r"[^A-Za-z0-9]+", "", zone.name)
    sheet.save(folder / f"{zone.ui_map_id}-{slug}.jpg", quality=88)  # photographic crops: PNG runs ~10 MB a sheet


# Overview

def render_overview(results: list[ZoneResult], palette: list[PaletteColor], opacity: tuple[float, float],
                    settings: Settings, path: Path) -> None:
    """Zones x colors in one image. Each cell's top half is the world map and its bottom half the minimap, each
    the zone's terrain where the color is faintest, with the blob fill blended into its middle. Banned cells are
    framed red."""
    fill_alpha = opacity[0]
    name_width, cell_width, cell_height, top = 200, 34, 38, 92
    results = sorted(results, key=lambda r: (r.zone.continent, r.zone.name))
    image = Image.new("RGB", (name_width + len(palette) * cell_width + 70, top + len(results) * cell_height + 10),
                      BACKGROUND)
    draw = ImageDraw.Draw(image)
    font, small = _font(14), _font(11)
    draw.text((10, 8), "Top: world map · bottom: minimap · each on the zone's terrain where the color is "
                       "faintest, blob fill in the middle · red frame: banned", fill=TEXT, font=font)
    draw.text((10, 28), _settings_text(settings), fill=DIM, font=small)

    # Palette header
    for i, color in enumerate(palette):
        x = name_width + i * cell_width
        draw.rectangle((x + 3, 50, x + cell_width - 3, 70), fill=color.rgb)
        draw.text((x + 8, 74), str(color.index), fill=DIM, font=small)

    for row, result in enumerate(results):
        y = top + row * cell_height
        draw.text((10, y + 11), f"{result.zone.name} ({result.zone.ui_map_id})", fill=TEXT, font=font)
        draw.text((name_width + len(palette) * cell_width + 10, y + 11), f"{len(result.banned)} banned",
                  fill=RED if result.banned else DIM, font=small)
        for i, color in enumerate(palette):
            x = name_width + i * cell_width
            for half, view in enumerate(("map", "minimap")):
                ground = np.array(min((t for t in result.terrains if t.view == view),
                                      key=lambda t: t.scores[color.index][0]).rgb, np.float32)
                blended = ground * (1 - fill_alpha) + np.array(color.rgb, np.float32) * fill_alpha
                y0, y1 = y + 2 + half * (cell_height - 4) // 2, y + 2 + (half + 1) * (cell_height - 4) // 2
                draw.rectangle((x + 2, y0, x + cell_width - 2, y1 - 1), fill=tuple(int(v) for v in ground))
                draw.rectangle((x + 8, y0 + 4, x + cell_width - 8, y1 - 5), fill=tuple(int(v) for v in blended))
            if color.index in result.banned:
                draw.rectangle((x + 1, y + 1, x + cell_width - 1, y + cell_height - 2), outline=RED, width=2)
    image.save(path, optimize=True)
